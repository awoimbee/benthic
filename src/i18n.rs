//! A small, dependency-free translation layer.
//!
//! Every user-facing string lives as a `&'static str` field on [`Strings`],
//! with one static instance per [`Language`]. Components read the language
//! from [`Preferences`](benthic_core::Preferences) and look up the table with
//! [`strings`]. Fields that take a value use `{}` placeholders and are
//! formatted with [`format!`].
//!
//! Adding a language is intentionally mechanical: add the variant to
//! [`Language`](benthic_core::Language), add a static table here, and return it
//! from [`strings`]. Adding a string means one field plus two translations.

use std::fmt::Display;

use benthic_core::Language;

/// Fill `template`'s `{}` placeholders, in order, with `args`.
pub fn fill(template: &str, args: &[String]) -> String {
    let mut out =
        String::with_capacity(template.len() + args.iter().map(String::len).sum::<usize>());
    let mut parts = template.split("{}");
    if let Some(first) = parts.next() {
        out.push_str(first);
    }
    for (arg, part) in args.iter().zip(parts) {
        out.push_str(arg);
        out.push_str(part);
    }
    out
}

/// Format a template with one value.
pub fn t1(template: &str, a: impl Display) -> String {
    fill(template, &[a.to_string()])
}

/// Format a template with two values.
pub fn t2(template: &str, a: impl Display, b: impl Display) -> String {
    fill(template, &[a.to_string(), b.to_string()])
}

/// Format a template with three values.
pub fn t3(template: &str, a: impl Display, b: impl Display, c: impl Display) -> String {
    fill(template, &[a.to_string(), b.to_string(), c.to_string()])
}

