impl Strings {
    /// Convenience for the static instance matching a language.
    fn for_language(language: Language) -> &'static Strings {
        match language {
            Language::English => &ENGLISH,
            Language::French => &FRENCH,
        }
    }
}

/// The translation table for `language`.
pub fn strings(language: Language) -> &'static Strings {
    Strings::for_language(language)
}

