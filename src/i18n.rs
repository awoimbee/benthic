impl Strings {
    /// Convenience for the static instance matching a language.
    fn for_language(language: Language) -> &'static Strings {
        match language {
            Language::English => &ENGLISH,
            Language::French => &FRENCH,
        }
    }
}

/// The translation table for `language`.
pub fn strings(language: Language) -> &'static Strings {
    Strings::for_language(language)
}

/// The translated name of a gear kind.
pub fn gear_kind(t: &Strings, kind: GearKind) -> &'static str {
    match kind {
        GearKind::Wetsuit => t.gear_kind_wetsuit,
        GearKind::Bottle => t.gear_kind_bottle,
        GearKind::WeightBelt => t.gear_kind_weights,
        GearKind::Bcd => t.gear_kind_bcd,
        GearKind::Regulator => t.gear_kind_regulator,
        GearKind::DiveComputer => t.gear_kind_computer,
        GearKind::Mask => t.gear_kind_mask,
        GearKind::Fins => t.gear_kind_fins,
        GearKind::Torch => t.gear_kind_torch,
        GearKind::Camera => t.gear_kind_camera,
        GearKind::Other => t.gear_kind_other,
    }
}

